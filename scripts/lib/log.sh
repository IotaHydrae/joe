#!/usr/bin/env bash
# =============================================================================
# joe lib/log — 共享日志与颜色辅助
# =============================================================================
# 供各安装器 / 命令复用, 避免在每个脚本里重复定义同一组函数。
# 只依赖 bash; 被 source 后即可使用。
#
# 两类风格并存:
#   - 颜色包装 c_g/c_r/c_y/c_b/c_d: 返回着色后的字符串 (供 printf 拼接)
#   - 标准日志 info/ok/warn/die: [INFO]/[SUCCESS]/[WARNING]/[ERROR] 前缀
# 需要箭头/勾叉风格输出的脚本 (sync-configs / quickstart) 在 source 本文件后
# 自行重定义 info/ok/warn(/die), 用 c_* 拼装即可, 不必重复颜色定义。
# =============================================================================

# 颜色包装: 接收要着色的文本, 输出带 ANSI 的字符串
c_g() { printf '\033[0;32m%s\033[0m' "$1"; }
c_r() { printf '\033[0;31m%s\033[0m' "$1"; }
c_y() { printf '\033[1;33m%s\033[0m' "$1"; }
c_b() { printf '\033[1;36m%s\033[0m' "$1"; }
c_d() { printf '\033[2m%s\033[0m' "$1"; }

# 标准日志行
info() { printf '\033[0;34m[INFO]\033[0m %s\n' "$*"; }
ok()   { printf '\033[0;32m[SUCCESS]\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m[WARNING]\033[0m %s\n' "$*"; }
die()  { printf '\033[0;31m[ERROR]\033[0m %s\n' "$*" >&2; exit 1; }
